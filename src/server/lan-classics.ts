import type { GameInput } from "./store.js";

function steamClassic(appid: number, name: string, note: string, tags: string[], minPlayers: number, maxPlayers: number, releaseDate = ""): GameInput {
  return {
    name,
    note,
    steamAppId: appid,
    coverUrl: `https://shared.cloudflare.steamstatic.com/store_item_assets/steam/apps/${appid}/header.jpg`,
    storeUrl: `https://store.steampowered.com/app/${appid}/`,
    releaseDate,
    minPlayers,
    maxPlayers,
    tags
  };
}

function curatorSteamClassic(appid: number, name: string, range: "2-4" | "5-8" | "9-16" | "17+", minPlayers: number, maxPlayers: number, releaseDate = ""): GameInput {
  return steamClassic(
    appid,
    name,
    `Steam-Curator LAN Party Games: ${range} Max Players`,
    ["Steam", "LAN-Party-Games", `${range} Spieler`],
    minPlayers,
    maxPlayers,
    releaseDate
  );
}

function steamDbLanCoop(appid: number, name: string, maxPlayers: number, tags: string[]): GameInput {
  return steamClassic(
    appid,
    name,
    "SteamDB: Most played LAN Co-op",
    ["SteamDB", "LAN Co-op", ...tags],
    2,
    maxPlayers
  );
}

function classic(name: string, note: string, tags: string[], minPlayers: number, maxPlayers: number, storeUrl = "", coverUrl = "", releaseDate = ""): GameInput {
  return {
    name,
    note,
    steamAppId: null,
    coverUrl,
    storeUrl,
    releaseDate,
    minPlayers,
    maxPlayers,
    tags
  };
}

